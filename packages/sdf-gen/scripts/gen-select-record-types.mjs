#!/usr/bin/env node
/**
 * Regenerates src/select-record-types.ts from the SuiteCloud SDK's metadata.
 *
 *   node packages/sdf-gen/scripts/gen-select-record-types.mjs [path/to/cli-<version>.jar]
 *
 * Reads sdf_metadata/list/generic_customfield_selectrecordtype.xml from the jar (default: the newest jar in
 * ~/.suitecloud-sdk/cli) with `unzip -p`, and fails if any <value> in the list is not captured.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const sdkDir = path.join(homedir(), ".suitecloud-sdk", "cli");
const jar =
  process.argv[2] ??
  path.join(sdkDir, readdirSync(sdkDir).filter((f) => /^cli-.*\.jar$/.test(f)).sort().at(-1) ?? "missing.jar");
const entry = "sdf_metadata/list/generic_customfield_selectrecordtype.xml";
const xml = execFileSync("unzip", ["-p", jar, entry], { encoding: "utf8" });

const all = xml.match(/<value\b/g)?.length ?? 0;
const values = [...xml.matchAll(/<value(?: feature="([A-Z0-9_]+)")?>(-[0-9]+)<\/value>/g)].map((m) => [m[2], m[1] ?? null]);
const skipped = all - values.length;
// Non-numeric values (custom list/record references) are out of scope; report them so a format change is noticed.
const nonNumeric = [...xml.matchAll(/<value(?: feature="[^"]*")?>([^<]*)<\/value>/g)].map((m) => m[1]).filter((v) => !/^-[0-9]+$/.test(v));
if (skipped !== nonNumeric.length) {
  console.error(`gen-select-record-types: ${skipped} values not captured but only ${nonNumeric.length} are non-numeric; check the regex`);
  process.exit(1);
}

const out = `/**
 * Standard record types a SELECT or MULTISELECT custom field may list, and the manifest feature each needs.
 * Generated by scripts/gen-select-record-types.mjs from ${entry} in ${path.basename(jar)}:
 * ${values.length} numeric values (${nonNumeric.length} non-numeric entries left out). Custom lists and custom record types are not included.
 */
export const SELECT_RECORD_TYPES: Readonly<Record<string, string | null>> = {
${values.map(([v, f]) => `  "${v}": ${f ? JSON.stringify(f) : "null"},`).join("\n")}
};
`;
writeFileSync(path.join(here, "../src/select-record-types.ts"), out);
console.log(`wrote ${values.length} values (${nonNumeric.length} non-numeric skipped: ${nonNumeric.join(", ") || "none"})`);
